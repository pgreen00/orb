import { readdirSync, readFileSync, writeFileSync } from "fs";
import { join } from "path";

const HEADER = `// AUTO-GENERATED by scripts/generate-pipe-manifest.mjs -- do not edit.
// Maps built-in pipe names to lazy loaders so each module becomes its own chunk
// and is only fetched the first time one of its pipes is used.
`;

/**
 * Extracts exported pipe names from a module's source. Recognizes
 * `export const name`, `export { a, b }` and `export default`. Type-only
 * exports are excluded since they don't exist at runtime.
 * @param {string} source
 * @returns {{ named: string[], hasDefault: boolean }}
 */
function findExports(source) {
  const named = new Set();

  for (const match of source.matchAll(
    /^export\s+(?:const|let|var|function|async\s+function)\s+([A-Za-z_$][\w$]*)/gm,
  )) {
    named.add(match[1]);
  }

  for (const match of source.matchAll(/^export\s*\{([^}]*)\}/gm)) {
    for (const clause of match[1].split(",")) {
      const trimmed = clause.trim();
      if (!trimmed || trimmed.startsWith("type ")) continue;
      const parts = trimmed.split(/\s+as\s+/);
      const name = (parts[1] ?? parts[0]).trim();
      if (name && name !== "default") named.add(name);
    }
  }

  for (const match of source.matchAll(
    /^export\s+(?:type|interface)\s+([A-Za-z_$][\w$]*)/gm,
  )) {
    named.delete(match[1]);
  }

  return {
    named: [...named],
    hasDefault: /^export\s+default\s/m.test(source),
  };
}

/**
 * Scans the built-in pipes directory and writes a name -> lazy loader manifest.
 *
 * Each exported pipe is registered under its export name; a module's default
 * export is registered under the module's file name.
 *
 * @param {object} options
 * @param {string} options.pipesDir Directory containing built-in pipe modules.
 * @param {string} options.outFile Path of the manifest module to write.
 * @returns {string[]} The registered pipe names, sorted.
 */
export function generatePipeManifest({ pipesDir, outFile }) {
  const files = readdirSync(pipesDir)
    .filter((file) => file.endsWith(".ts") && !file.endsWith(".d.ts"))
    .sort();

  /** @type {Map<string, { module: string, accessor: string }>} */
  const entries = new Map();

  const claim = (name, module, accessor) => {
    const existing = entries.get(name);
    if (existing) {
      throw new Error(
        `Duplicate built-in pipe "${name}" in ${module}.ts and ${existing.module}.ts; ` +
          `pipe names must be unique across modules.`,
      );
    }
    entries.set(name, { module, accessor });
  };

  for (const file of files) {
    const module = file.replace(/\.ts$/, "");
    const source = readFileSync(join(pipesDir, file), "utf8");
    const { named, hasDefault } = findExports(source);

    if (hasDefault) {
      claim(module, module, "m.default");
    }
    for (const name of named) {
      claim(name, module, `m.${name}`);
    }
  }

  const names = [...entries.keys()].sort();
  const lines = names.map((name) => {
    const { module, accessor } = entries.get(name);
    return `  ${JSON.stringify(name)}: () => import("./pipes/${module}.js").then((m) => ${accessor}),`;
  });

  const contents = `${HEADER}
import type { Pipe } from "../../utils/pipes.js";

export const builtinPipes: Record<string, () => Promise<Pipe>> = {
${lines.join("\n")}
};
`;

  writeFileSync(outFile, contents, "utf8");
  return names;
}
